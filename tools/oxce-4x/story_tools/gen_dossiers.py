"""Dossier text for the Intel files (STORY, 14 Nov 2026; brief: claude/BRIEF_FOR_BUILD_Dossiers.txt).
Source: the 213 pages generated 11 Nov in the design repo (dossiers/en-US_characters_11nov.yml).
Refresh: for every character ROSTER has a record for (roster/roster_*.yaml), the rank, specialty,
signature weapon, trait and move lines are rewritten from ROSTER's record and text (gijoe_roster_text.rul).
The dossier paragraph and the quote are kept. Output: mod/Ruleset/gijoe_dossiers_text.rul (extraStrings only;
BUILD writes the ufopaedia entries)."""
import sys, glob, re, yaml, os
HERE = os.path.dirname(os.path.abspath(__file__)); TOOLS = os.path.dirname(HERE)
RD = sys.argv[1] if len(sys.argv) > 1 else os.path.join(TOOLS, 'mod', 'Ruleset')
src = yaml.safe_load(open(os.path.join(HERE, 'dossiers', 'en-US_characters_11nov.yml')))['en-US']
S = {}
for e in yaml.safe_load(open(os.path.join(RD, 'gijoe_roster_text.rul'))).get('extraStrings', []):
    if e.get('type') == 'en-US': S.update(e['strings'])
recs = {}
for f in sorted(glob.glob(os.path.join(TOOLS, 'roster', 'roster_*.yaml'))):
    y = yaml.safe_load(open(f))
    for r in (y['characters'] if 'characters' in y else list(y.values())[0]): recs[r['id']] = r
NL = '{NEWLINE}'
def s(k): return S.get(k, '') if k else ''
out = dict(src); changed = []
for cid, r in recs.items():
    key = 'STR_ART_%s_TEXT' % cid[2:]
    if cid in ('C_TOMAX', 'C_XAMOT'): continue  # the twins share one page (STR_ART_TOMAX_AND_XAMOT); kept as written
    if key not in src: print('no page for', cid); continue
    lines = src[key].split(NL)
    # line 1: faction - rank
    if r.get('rankString') and s(r['rankString']) and r.get('rank') and 'canon' not in str(r.get('rank')):
        fac = lines[1].split(' - ')[0]
        lines[1] = '%s - %s (%s)' % (fac, s(r['rankString']), r['rank'])
    spec = '; '.join(x for x in (s(r.get('primary')), s(r.get('secondary'))) if x)
    tr = r.get('trait') or {}; mv = r.get('move') or {}; wp = (r.get('weapon') or {}).get('name')
    if wp:  # drop ROSTER's source notes, keep what the weapon is
        wp = re.sub(r'\s*\((?:[^)]*\b(?:toy|3DJoes|Catalog|game default)\b[^)]*)\)', '', wp)
        wp = re.sub(r';\s*pistol as game default', '', wp).strip()
    new = []
    for ln in lines:
        if ln.startswith('Specialty:') and spec: ln = 'Specialty: ' + spec
        elif ln.startswith('Signature weapon:') and wp: ln = 'Signature weapon: ' + wp
        elif ln.startswith('Trait:') and tr.get('name'): continue  # replaced by the Signature trait line
        elif ln.startswith('Signature move:') and mv.get('name'):
            if tr.get('name'): new.append('Signature trait: %s: %s' % (s(tr['name']), s(tr.get('desc'))))
            ln = 'Signature move: %s: %s' % (s(mv['name']), s(mv.get('desc')))
        new.append(ln)
    if not any(l.startswith('Signature trait:') for l in new) and tr.get('name'):
        i = max(i for i, l in enumerate(new) if l.startswith('Signature')) + 1
        new.insert(i, 'Signature trait: %s: %s' % (s(tr['name']), s(tr.get('desc'))))
    t = NL.join(new)
    if t != src[key]: changed.append(cid)
    out[key] = t
hdr = '# GENERATED by story_tools/gen_dossiers.py: do not hand-edit. Dossier text for the Intel files (213 pages).\n'
with open(os.path.join(RD, 'gijoe_dossiers_text.rul'), 'w') as f:
    f.write(hdr); yaml.safe_dump({'extraStrings': [{'type': 'en-US', 'strings': out}]}, f, allow_unicode=True, width=10**6, sort_keys=False)
print('dossier strings: %d, refreshed from ROSTER: %d' % (len(out), len(changed)))
