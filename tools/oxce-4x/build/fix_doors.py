#!/usr/bin/env python3
"""Doors you can walk through, and break with a sensible number of shots (John 15 Nov: "the doors took a ton of
shots to get through and were locked").

    python3 build/fix_doors.py

The map kit writes every door with TU_Walk 255. The pathfinder reads 255 as a wall, so no unit ever plans a route
through a closed door: they act locked. Vanilla doors are passable (URBAN: 8). This writes
mod/Ruleset/zz_gijoe_doors.rul, an MCDPatch per terrain set (patches merge with the destruction profile's) that:
- makes every closed door (door or UFO-door flag) with TU 255 passable: TUWalk / TUSlide / TUFly 4;
- sets its armour by what it is: up to 30 (wooden, glass, screen) -> 12, 31-100 (steel, shop) -> 25, over 100
  (the Pit's blast doors, vaults, ship hatches) left alone. A tile takes no damage that doesn't beat its armour in
  one hit, so a door at 60-90 against rifles was close to unbreakable.
Rerun after any map pack lands with new terrain.
"""
import glob
import os
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.join(HERE, '..', 'mod')

patches = []
count = 0
for f in sorted(glob.glob(os.path.join(MOD, 'TERRAIN', '*.MCD'))):
    d = open(f, 'rb').read()
    rows = []
    for i in range(len(d) // 62):
        r = d[i * 62:(i + 1) * 62]
        if not (r[35] or r[30]) or r[39] != 255:
            continue
        p = {'MCDIndex': i, 'TUWalk': 4, 'TUSlide': 4, 'TUFly': 4}
        a = r[42]
        if a <= 30 and a > 12:
            p['armor'] = 12
        elif 30 < a <= 100:
            p['armor'] = 25
        rows.append(p)
    if rows:
        patches.append({'type': os.path.basename(f)[:-4], 'data': rows})
        count += len(rows)
out = os.path.join(MOD, 'Ruleset', 'zz_gijoe_doors.rul')
with open(out, 'w') as fh:
    fh.write('# GENERATED by build/fix_doors.py: closed doors passable (the kit wrote TU 255) and breakable. Do not edit.\n')
    fh.write(yaml.safe_dump({'MCDPatches': patches}, sort_keys=False, width=140))
print('%d doors in %d terrain sets' % (count, len(patches)))
