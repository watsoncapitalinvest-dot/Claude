      ('STR_COMPUTER_STATION', 159, 1, 80000, 8, 3000, {}),
      ('STR_JOE_COMMS_CENTER', 202, 1, 100000, 8, 3000, {}),            # art requested (BRIEF_FOR_GRAPHICS_AI_Armory_CommsRoom)
