"""Put every stock deployment that still carries X-COM's alien weapon ladder on the six-tier one.

usage: gen_cobra_kit.py <vanilla alienDeployments.rul> <out.rul>

The generated Cobra sites get the ladder in gen_cobra_sites.py. These are the rest - terror
attacks, crash sites, landings, base defence - which the mod fights on the stock deployments and
which would otherwise hand a month-1 trooper a pulse pistol. Only the itemSets change, and only
where they are the stock three-rung ladder; the same six_tier() as the sites, so one ladder.
"""
import sys, yaml
VANILLA, OUT = sys.argv[1], sys.argv[2]
src = open(__file__.replace('gen_cobra_kit.py', 'gen_cobra_sites.py')).read()
ns = {}
exec(src[src.index('EARLY = ['):src.index('terror = load_entry')], ns)

out = []
for dep in yaml.safe_load(open(VANILLA))['alienDeployments']:
    data = dep.get('data')
    if not data:
        continue
    sets = [e.get('itemSets', []) for e in data]
    if not any(len(s) == 3 and any(s) for s in sets):
        continue
    out.append({'type': dep['type'], 'data': ns['six_tier'](data)})

head = ('# GENERATED by build/gen_cobra_kit.py - do not hand-edit.\n'
        '# The stock deployments the mod still fights, put on the six-tier weapon ladder\n'
        '# (months 1-3 handguns ... 31+ heavy pulse). Only `data` is overridden.\n')
open(OUT, 'w').write(head + yaml.dump({'alienDeployments': out}, sort_keys=False, width=200))
print('wrote %s: %d deployments' % (OUT, len(out)), ', '.join(d['type'] for d in out))
