#!/usr/bin/env python3
"""Write mod/Ruleset/gijoe_maps_emmaville.rul from MAPS' Emmaville samples folder.

usage: gen_emmaville_rul.py SAMPLES_DIR OUT_RUL

Each sample piece carries <NAME>_spots.json (its size) and <NAME>_terrain.json (its own terrain
list, in the order its .MAP2 part ids assume). One terrain per piece; New Battle deployments group
pieces of the same size. A piece with no route nodes cannot place the Joes, so it gets a terrain but
is left out of the deployments until MAPS gives it nodes.
"""
import glob, json, re, sys

samples, out_path = sys.argv[1], sys.argv[2]
out = ["# Emmaville (MAPS, BRIEF_FOR_BUILD_Emmaville v7, 14 Nov): sample pieces of the planned city, each a .MAP2 with",
       "# its OWN terrain list (the order is the piece's <NAME>_terrain.json, which the .MAP2 ids assume).",
       "# GENERATED by build/gen_emmaville_rul.py from MAPS' samples folder; edit the script, not this file.",
       "# v8 (14 Nov 20:55): 7 levels, level 0 the underground (sewers, subway, tunnels), the city on 1-6, ground = level 1.",
       "# Node ranks: 0 civilians, 1 Joe start (south edge), 2 hostiles. New Battle only: no campaign mission sends a piece yet.",
       "terrains:"]
pieces = []
for d in sorted(glob.glob(samples.rstrip("/") + "/*/")):
    sp = json.load(open(glob.glob(d + "*_spots.json")[0]))
    n, w, l, h = re.match(r"(\S+) (\d+) x (\d+) x (\d+)", sp["map"]).groups()
    w, l, h = int(w), int(l), int(h)
    sets = json.load(open(glob.glob(d + "*_terrain.json")[0]))["mapDataSets"]
    pieces.append((n, w, l, h, bool(sp.get("nodes"))))
    out += [f"  - name: {n}", f"    mapDataSets: [{', '.join(sets)}]",
            f"    mapBlocks:", f"      - {{name: {n}, width: {w}, length: {l}, height: {h}}}"]
# a map is laid out in 10-tile cells: a piece that isn't a multiple of 10 (COBRA_LAIR, 64 x 48) sits in the
# corner of a map rounded up to the next 10, the strip beyond it left empty
def cells(n): return (n + 9) // 10
out.append("\nmapScripts:")
for w, l in sorted({(p[1], p[2]) for p in pieces}):
    out += [f"  - type: EMMA_SCRIPT_{w}x{l}", "    commands:", "      - type: addBlock",
            f"        size: [{cells(w)}, {cells(l)}]", "        rects:", f"          - [0, 0, {cells(w)}, {cells(l)}]"]

def group(n):
    for key, tag in (("STR_MAP_COBRA_LAIR", "COBRA_LAIR"), ("STR_MAP_EMMA_UNDERGROUND", "EMMA_U_"), ("STR_MAP_EMMA_SEWER", "SEWER"), ("STR_MAP_EMMA_BRIDGE", "BRIDGE"), ("STR_MAP_EMMA_WEIR", "WEIR"), ("STR_MAP_EMMA_LANDMARK", "_LM_")):
        if tag in n: return key
    return "STR_MAP_EMMAVILLE"

groups = {}
for p in pieces:
    if p[4]: groups.setdefault(group(p[0]), []).append(p)
out.append("\nalienDeployments:")
for k, ps in groups.items():
    w, l, h = ps[0][1:4]
    assert all(p[1:3] == (w, l) for p in ps), k
    out.append(f"""  - type: {k}
    data:
      - alienRank: 5
        lowQty: 8
        highQty: 10
        dQty: 1
        percentageOutsideUfo: 100
        itemSets:
          - [STR_PISTOL, STR_PISTOL_CLIP, STR_PISTOL_CLIP]
          - [STR_RIFLE, STR_RIFLE_CLIP, STR_RIFLE_CLIP]
          - [STR_RIFLE, STR_RIFLE_CLIP, STR_RIFLE_CLIP]
    civilians: 12
    width: {cells(w) * 10}
    length: {cells(l) * 10}
    height: {h}
    terrains: [{', '.join(p[0] for p in ps)}]
    script: EMMA_SCRIPT_{w}x{l}
    shade: 0
    briefing: {{palette: 0, title: {k}, desc: STR_MAP_EMMAVILLE_BRIEFING}}""")
titles = {"STR_MAP_EMMAVILLE": "Emmaville", "STR_MAP_EMMA_UNDERGROUND": "Emmaville underground", "STR_MAP_COBRA_LAIR": "Cobra lair (Old Mill)", "STR_MAP_EMMA_LANDMARK": "Emmaville landmark", "STR_MAP_EMMA_WEIR": "Emmaville weir",
          "STR_MAP_EMMA_BRIDGE": "Emmaville bridge", "STR_MAP_EMMA_SEWER": "Emmaville sewer"}
out.append("\nextraStrings:\n  - type: en-US\n    strings: &emmastr")
out += [f'      {k}: "{v}"' for k, v in titles.items()]
out.append('      STR_MAP_EMMAVILLE_BRIEFING: "A piece of Emmaville. Cobra is in the buildings."')
out += [f'      MAP_{p[0]}: "{p[0][5:] if p[0].startswith("EMMA_") else p[0].replace("_LM_", " ").replace("LM_", "").replace("_", " ").title()}"' for p in pieces]
out.append("  - type: en-GB\n    strings: *emmastr\n")
open(out_path, "w").write("\n".join(out))
print("left out (no nodes):", [p[0] for p in pieces if not p[4]])
