"""Cobra's research tree into the game (BRIEF_FOR_BUILD_Act1Fixes item 5, approved 16 Nov; John 17 Nov 01:35 "build time").

Reads STORY's story_tools/cobra_tree.yml (92 topics, 12 departments) and writes mod/Ruleset/zz_gijoe_cobra_tree.rul as
the game's cobraProjects list. That list used to live at the bottom of gijoe_cobra_economy.rul (26 placeholders); it was
moved out because OXCE appends top-level lists, so two files would have run two trees at once.

Kept from the old list because the game already relies on it: STR_COBRA_PIT_ESCAPE_TUNNEL (John 16 Nov 11:07, the Pit
surface battle reads it). Every topic carries its requires and unlocks; the engine starts a topic only when its requires
are done and its earliest month has come, and a topic past its latest month gets double effort, never forced (John 10:01:
"incentivize, never force"). Only kitTier unlocks change anything today; the rest are stored for the hooks to come.
usage: python3 build/gen_cobra_projects.py
"""
import os, yaml
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'story_tools', 'cobra_tree.yml')
OUT = os.path.join(HERE, '..', 'mod', 'Ruleset', 'zz_gijoe_cobra_tree.rul')
T = yaml.safe_load(open(SRC))['cobraResearchTopics']
out = []
for t in T:
    e = {'type': t['type'], 'department': t['department'], 'cost': int(t.get('cost') or 0),
         'materielPerProgress': int(t.get('materielPerProgress') or 0)}
    for u in t.get('unlocks') or []:
        if u.startswith('kitTier:'):
            e['unlocksKitTier'] = int(u.split(':')[1])
    if t.get('doneAtStart'):
        e['doneAtStart'] = True
    if t.get('earliestMonth') is not None:
        e['earliestMonth'] = int(t['earliestMonth'])
    if t.get('latestMonth') is not None:
        e['latestMonth'] = int(t['latestMonth'])
    if t.get('requires'):
        e['requires'] = list(t['requires'])
    if t.get('unlocks'):
        e['unlocks'] = [str(u) for u in t['unlocks']]
    out.append(e)
if not any(e['type'] == 'STR_COBRA_PIT_ESCAPE_TUNNEL' for e in out):
    find = [e for e in out if 'FIND_THE_PIT' in e['type']]
    out.append({'type': 'STR_COBRA_PIT_ESCAPE_TUNNEL', 'department': 'INTELLIGENCE', 'cost': 260, 'materielPerProgress': 6,
                'earliestMonth': 30, 'requires': [find[0]['type']] if find else [], 'unlocks': ['mission:Pit escape tunnel team']})
hdr = ('# GENERATED by build/gen_cobra_projects.py from story_tools/cobra_tree.yml (STORY): edit the tree there, not here.\n'
       '# Cobra\'s research: one topic at a time per department, in this order; a topic starts once its requires are done and\n'
       '# its earliestMonth has come; past latestMonth it gets double effort (never forced).\n')
open(OUT, 'w').write(hdr + yaml.safe_dump({'cobraProjects': out}, sort_keys=False, width=160))
print(len(out), 'topics ->', os.path.relpath(OUT))
