#!/usr/bin/env python3
"""Wire John's sound-board picks into the mod.

usage: gen_sounds.py PICKS_JSON POOL_DIR MOD_DIR

PICKS_JSON  the board's saved document ({"picks": {slot: "12, 14"}}).
POOL_DIR    the numbered, game-ready WAVs (NNN.wav) and pool.json (name, pack, licence).
MOD_DIR     tools/oxce-4x/mod

Free sounds (CC0 / CC-BY) are copied to Resources/SFX/ and committed.
Sounds whose licence is unknown go to Resources/Sound/sfx/, which .gitignore keeps
out of the public repo; they reach the game in the update zip.
Battlescape sounds get mod indices 300+N (N = board number). World-map and menu
sounds replace the original GEO.CAT slots.
"""
import json, os, re, shutil, sys

picks_f, pool_d, mod_d = sys.argv[1:4]
picks = json.load(open(picks_f))["picks"]
pool = {e["n"]: e for e in json.load(open(os.path.join(pool_d, "pool.json")))}

def nums(slot):
    return [int(x) for x in re.findall(r"\d+", picks.get(slot, "") or "") if int(x) in pool]

used = set()
def path(n):
    used.add(n)
    sub = "Resources/Sound/sfx" if pool[n]["lic"] == "unknown" else "Resources/SFX"
    return f"{sub}/gj_{n:03d}.wav"
def idx(ns):
    for n in ns: path(n)
    return [300 + n for n in ns]

# battlescape items: slot -> (field, [items])
ITEM = [
    ("uzi", "fireSound", ["STR_PISTOL"]),
    ("m4", "fireSound", ["STR_RIFLE"]),
    ("sniper", "fireSound", ["STR_LASER_RIFLE"]),
    ("hmg", "fireSound", ["STR_HEAVY_CANNON"]),
    ("m32", "fireSound", ["STR_AUTO_CANNON"]),
    ("rpg", "fireSound", ["STR_ROCKET_LAUNCHER"]),
    ("ppistol", "fireSound", ["STR_PLASMA_PISTOL"]),
    ("prifle", "fireSound", ["STR_PLASMA_RIFLE"]),
    ("pheavy", "fireSound", ["STR_HEAVY_PLASMA"]),
    ("tranq", "fireSound", ["STR_TRANQ_GUN"]),
    ("torch", "fireSound", ["STR_CUTTING_TORCH"]),
    ("airgun", "fireSound", ["STR_AF_GUN_SKYSTRIKER", "STR_AF_GUN_CONQUEST", "STR_AF_GUN_PHANTOM",
                             "STR_AF_GUN_RATTLER", "STR_AF_GUN_FIREBAT", "STR_AF_GUN_CONDOR_TAIL"]),
    ("seagun", "fireSound", ["STR_SEA_DEVILFISH_GUN", "STR_SEA_SHARC_GUN", "STR_SEA_SLED_GUN",
                             "STR_SEA_DECK_GUN", "STR_SEA_AA_GUN"]),
    ("seaweap", "fireSound", ["STR_SEA_TORPEDO_TUBE", "STR_SEA_DEPTH_CHARGE", "STR_SEA_MINE_RACK"]),
    ("reload", "reloadSound", ["STR_PISTOL", "STR_RIFLE", "STR_HEAVY_CANNON", "STR_AUTO_CANNON",
                               "STR_ROCKET_LAUNCHER", "STR_TRANQ_GUN"]),
    # hits: bullets land through the clip; the sniper rifle carries its own (no clip)
    ("bhit", "hitSound", ["STR_PISTOL_CLIP", "STR_RIFLE_CLIP", "STR_HC_AP_AMMO", "STR_LASER_RIFLE"]),
    ("phit", "hitSound", ["STR_PLASMA_PISTOL_CLIP", "STR_PLASMA_RIFLE_CLIP", "STR_HEAVY_PLASMA_CLIP"]),
    ("seahit", "hitSound", ["STR_AF_GUN_SKYSTRIKER", "STR_AF_GUN_CONQUEST", "STR_AF_GUN_PHANTOM",
                            "STR_AF_GUN_RATTLER", "STR_AF_GUN_FIREBAT", "STR_AF_GUN_CONDOR_TAIL",
                            "STR_SEA_DEVILFISH_GUN", "STR_SEA_SHARC_GUN", "STR_SEA_SLED_GUN",
                            "STR_SEA_DECK_GUN", "STR_SEA_AA_GUN"]),
    ("large", "hitSound", ["STR_GRENADE", "STR_ALIEN_GRENADE", "STR_HIGH_EXPLOSIVE", "STR_PROXIMITY_GRENADE",
                           "STR_HC_HE_AMMO", "STR_HC_I_AMMO", "STR_AC_HE_AMMO", "STR_AC_I_AMMO",
                           "STR_SMALL_ROCKET", "STR_LARGE_ROCKET", "STR_INCENDIARY_ROCKET"]),
]
items = {}
for slot, field, names in ITEM:
    ns = nums(slot)
    if not ns: continue
    for it in names:
        items.setdefault(it, {})[field] = idx(ns)

# GEO.CAT: replace the original slots (one file each)
GEO = [("button", 0), ("popup1", 1), ("popup2", 2), ("popup3", 3), ("ufofire", 8),
       ("ufocrash", 10), ("ufoexplode", 11), ("ufohit", 12), ("ourexplode", 13)]
geo = {}
for slot, i in GEO:
    ns = nums(slot)
    if ns: geo[i] = path(ns[0])

# battlescape constants that take one sound
const = {}
for slot, key in [("large", "largeExplosion"), ("small", "smallExplosion"),
                  ("door", "doorSound"), ("slideopen", "slidingDoorSound"),
                  ("slideclose", "slidingDoorClose"), ("drop", "itemDrop"), ("throw", "itemThrow")]:
    ns = nums(slot)
    if ns: const[key] = idx(ns[:1])[0]

L = ["# G.I. Joe sound effects: generated by tools/oxce-4x/build/gen_sounds.py from John's sound-board picks.",
     "# Do not hand-edit; change the picks and re-run.",
     "# Resources/SFX = free sounds (CC0; gj_175 is Michel Baradari, CC-BY 3.0, see CREDITS_SOUND.txt).",
     "# Resources/Sound/sfx = licence not yet known: kept out of the public repo, delivered in the update zip.",
     "", "extraSounds:", "  - type: BATTLE.CAT", "    files:"]
for n in sorted(used):
    if any(300 + n in v for d in items.values() for v in d.values()) or 300 + n in const.values():
        L.append(f"      {300+n}: {path(n)}   # {pool[n]['name']}")
L += ["  - type: GEO.CAT", "    files:"]
for i in sorted(geo):
    n = int(re.search(r"gj_(\d+)", geo[i]).group(1))
    L.append(f"      {i}: {geo[i]}   # {pool[n]['name']}")
if const:
    L += ["", "constants:"] + [f"  {k}: {v}" for k, v in const.items()]
L += ["", "items:"]
for it in sorted(items):
    L.append(f"  - type: {it}")
    for f, v in items[it].items():
        L.append(f"    {f}: [{', '.join(map(str, v))}]")
open(os.path.join(mod_d, "Ruleset", "zzz_gijoe_sounds.rul"), "w").write("\n".join(L) + "\n")

for n in sorted(used):
    dst = os.path.join(mod_d, path(n))
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy(os.path.join(pool_d, f"{n:03d}.wav"), dst)
free = sum(1 for n in used if pool[n]["lic"] != "unknown")
print(f"{len(used)} sounds: {free} free (committed), {len(used)-free} licence unknown (zip only); "
      f"{len(items)} items, {len(geo)} GEO slots, {len(const)} constants")
