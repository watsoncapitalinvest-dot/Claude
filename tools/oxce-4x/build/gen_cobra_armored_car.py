"""The Cobra armored-car job (John 18 Nov 17:39 "turn it into a cobra version"; NOTE_FOR_STORY_CobraArmoredCar_18Nov).
A copy of the cartel's STR_ARMORED_CAR_AMBUSH (gijoe_maps_ambush.rul) as STR_COBRA_ARMORED_CAR: same map, cash and getaway;
Cobra troopers (race STR_COBRA, the calendar's kit - handguns in months 1-3) instead of cartel gunmen, no cartel leader.
Writes mod/Ruleset/zz_gijoe_cobra_armored_car.rul. STORY's words replace the placeholders when they come.
"""
import os, copy, yaml
HERE = os.path.dirname(os.path.abspath(__file__)); RS = os.path.join(HERE, '..', 'mod', 'Ruleset')
doc = yaml.safe_load(open(os.path.join(RS, 'gijoe_maps_ambush.rul')))
src = next(d for d in doc['alienDeployments'] if d.get('type') == 'STR_ARMORED_CAR_AMBUSH')
d = copy.deepcopy(src)
d['type'] = 'STR_COBRA_ARMORED_CAR'
d['race'] = 'STR_COBRA'
for blk in d.get('data', []):
    blk.pop('customUnitType', None)          # Cobra's own men; the senior one leads
d.pop('robberLeader', None)
d.pop('missionCompleteText', None)
d['briefing'] = dict(d.get('briefing') or {}, title='STR_COBRA_ARMORED_CAR', desc='STR_BRIEFING_COBRA_ARMORED_CAR')
for k in ('markerName',):
    if k in d: d[k] = d[k]
out = {'alienDeployments': [d], 'extraStrings': [{'type': t, 'strings': {
    'STR_COBRA_ARMORED_CAR': 'Cobra Robbery',
    'STR_BRIEFING_COBRA_ARMORED_CAR': "Men in blue with snake patches are taking an armored car outside {TOWN}. No cartel this time: "
        "this money is going to Cobra. Stop them before the van gets away. [BUILD-1 placeholder for STORY]",
}} for t in ('en-US', 'en-GB')]}
open(os.path.join(RS, 'zz_gijoe_cobra_armored_car.rul'), 'w').write(
    '# GENERATED by build/gen_cobra_armored_car.py from STR_ARMORED_CAR_AMBUSH: edit the script, not this file.\n'
    + yaml.safe_dump(out, sort_keys=False, width=140))
print('written', len(d.get('data', [])), 'groups')
