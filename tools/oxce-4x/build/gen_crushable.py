"""Which tiles a tank drives through (John 18 Nov: "Tanks should run over sandbags").

Writes mod/Ruleset/zz_gijoe_crushable.rul: an MCDPatch per terrain with gjCrush: true on every
light obstacle - sandbags, fences, hedges, crops, hay, brush, wooden crates and pallets,
camouflage netting, razor wire. A big ground vehicle (Pathfinding::gjCrusher: 2x2 or larger,
not flying, not a soldier) may drive into one for 4 TU (an object) or 2 (a wall) and
flattens it as the hull rolls in (UnitWalkBState gjCrushUnder). Nothing else changes: men
still climb round them and shots still stop on them.

NOT crushed, on purpose: steel crates (crate_cobra, crate_stack), barrels (they explode),
the mine rail (NAMTN 'rail' is track, not a fence), walls, doors, consoles, trees.

The names come from the tile builders' names.json (the same lists tag_materials.py reads), which
live outside the repo - so this file's output is the record, and the input folder is an argument.
BARN and CULTIVAT are X-COM's own and have no names: their 'light' tiles in tag_materials.VANILLA
(hay bales, crops, fences, read off the art) are used.

usage: python3 build/gen_crushable.py <folder holding natiles/ cobratiles/ wildtiles/ mtntiles/ tiles/>
"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'mod', 'Ruleset', 'zz_gijoe_crushable.rul')
SETS = {'natiles': 'NAMER', 'cobratiles': 'COBRA', 'wildtiles': 'NAWILD', 'mtntiles': 'NAMTN', 'tiles': 'GIJOE'}
CRUSH = re.compile(r'^(sandbag|sandbags|hedge|picket|chain|razor|camonet|bush|corn|flowers|haybale|sage|pallet|crate_wood|crate$)')
FENCE_RAIL = {'NAMER'}          # 'rail' is a split-rail fence on the farm set only
# Sets with no names, read off a contact sheet with the MCD index on each tile (18 Nov). OUTYARD: chain-link
# and slat fence panels and gates (20, 22, 31, 33, 35, 44), sandbags (51), wooden crates (55, 56). OUTBASE:
# cardboard boxes (37). Left standing: concrete barriers, brick, drums, lockers, the ammo crates.
BY_EYE = {'OUTYARD': (20, 22, 31, 33, 35, 44, 51, 55, 56), 'OUTBASE': (37,)}
VANILLA_LIGHT = {               # tag_materials.VANILLA, the 'light' tiles
    'BARN': (3, 4, 10, 11, 12, 13, 14, 23),
    'CULTIVAT': (4, 5, 8, 11, 16, 17, 18, 19, 21, 22, 23, 24, 27, 28, 33, 34, 36),
}


def main():
    root = sys.argv[1]
    out, report = {}, []
    for folder, terrain in SETS.items():
        names = json.load(open(os.path.join(root, folder, 'names.json')))
        idx = [i for i, n in enumerate(names) if CRUSH.match(n) or (terrain in FENCE_RAIL and n.startswith('rail_'))]
        out[terrain] = idx
        report.append('%-7s %s' % (terrain, ', '.join('%d %s' % (i, names[i]) for i in idx)))
    for terrain, idx in VANILLA_LIGHT.items():
        out[terrain] = list(idx)
        report.append('%-7s %s (X-COM, read off the art)' % (terrain, ', '.join(map(str, idx))))
    for terrain, idx in BY_EYE.items():
        out[terrain] = list(idx)
        report.append('%-7s %s (read off the art)' % (terrain, ', '.join(map(str, idx))))
    lines = ['# GENERATED by build/gen_crushable.py - do not hand-edit.',
             '# Tiles a tank drives through and flattens (John 18 Nov). gjCrush: MCDPatch key read by the engine.',
             '#']
    lines += ['#   ' + r for r in report]
    lines += ['', 'MCDPatches:']
    for terrain, idx in out.items():
        if not idx: continue
        lines.append('  - type: %s' % terrain)
        lines.append('    data:')
        for i in idx:
            lines.append('      - MCDIndex: %d' % i)
            lines.append('        gjCrush: true')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print('\n'.join(report)); print('wrote', OUT, sum(len(v) for v in out.values()), 'tiles')


if __name__ == '__main__':
    main()
