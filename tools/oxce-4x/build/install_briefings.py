#!/usr/bin/env python3
"""Mission briefing pictures -> the game (STORY's BRIEF_FOR_BUILD_FirstHour item 4, BRIEF_FOR_BUILD_CobraTurnScreen).

    python3 build/install_briefings.py <dir with brief_*.png / cobra_turn_*.png> [...]

Each 1920x1200 picture becomes Resources/Backgrounds/Briefings/<name>.png (320x200, 8-bit, what the engine lays out on)
+ <name>_hi.png (the full picture, what the HD layer shows), and an extraSprite BRIEF_<NAME>.SCR in
Ruleset/gijoe_briefing_pictures.rul. A deployment names it as `briefing: {background: BRIEF_<NAME>.SCR}`.
The sources are John's (Reference\\cartel_briefings.zip, briefings_ranch_factory.zip, cobra_turn_redo.zip).
"""
import glob, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from PIL import Image
from install_screen_backgrounds import fit, to_8bit

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.normpath(os.path.join(HERE, '..', 'mod'))
OUT = os.path.join(MOD, 'Resources', 'Backgrounds', 'Briefings')
RUL = os.path.join(MOD, 'Ruleset', 'gijoe_briefing_pictures.rul')

os.makedirs(OUT, exist_ok=True)
for d in sys.argv[1:]:
    for f in sorted(glob.glob(os.path.join(d, '**', '*.png'), recursive=True)):
        n = os.path.basename(f)[:-4]
        if not (n.startswith('brief_') or n.startswith('cobra_turn_')):
            continue
        hi = fit(Image.open(f))
        hi.save(os.path.join(OUT, n + '_hi.png'))
        to_8bit(hi).save(os.path.join(OUT, n + '.png'))
        print('installed', n)
names = sorted(os.path.basename(p)[:-4] for p in glob.glob(os.path.join(OUT, '*.png')) if not p.endswith('_hi.png'))
with open(RUL, 'w') as o:
    o.write('# GENERATED by build/install_briefings.py: mission briefing and Cobra-turn pictures. Do not edit.\n')
    o.write('# A deployment shows one with  briefing: {background: BRIEF_<NAME>.SCR}.\nextraSprites:\n')
    for n in names:
        o.write('  - type: BRIEF_%s.SCR\n    singleImage: true\n    width: 320\n    height: 200\n    files:\n'
                '      0: Resources/Backgrounds/Briefings/%s.png\n' % (n.upper().replace('BRIEF_', '', 1), n))
print(len(names), 'pictures in', RUL)
