"""Cobra's ninth site type: the AIRSTRIP, the FANG Operating Base its bombers fly from (COBRA_OUTPOSTS_v1 s.1:
John 12:23 "A" - a bomber squadron is 3 Rattlers at a Cobra airstrip; AIR_RAID_DESIGN_v1 s.1: no bombers, no raids).

Cloned from what already works rather than written out: the factory site's deployment (its garrison and map), the
depot's build mission and its mission script. The economy entry (cost, upkeep, needsProject: STR_COBRA_RATTLER,
bombers: 3) is hand-written in gijoe_cobra_economy.rul with the other eight.

A STAND-IN until COBRA_OUTPOSTS_v1 settles what an airstrip looks like: its map is the factory site's map.

usage: python3 build/gen_cobra_airstrip.py   (reads and writes under mod/Ruleset)
"""
import copy, os, yaml

HERE = os.path.dirname(os.path.abspath(__file__))
RUL = os.path.join(HERE, '..', 'mod', 'Ruleset')

src = yaml.safe_load(open(os.path.join(RUL, 'gijoe_cobra_sites.rul')))
dep = copy.deepcopy(next(d for d in src['alienDeployments'] if d['type'] == 'STR_COBRA_FACTORY_SITE'))
dep['type'] = 'STR_COBRA_AIRSTRIP_SITE'
dep['markerName'] = 'STR_COBRA_AIRSTRIP'
dep['cobraSiteType'] = 'STR_COBRA_AIRSTRIP'
for k in ('genMission', 'genMissionFreq'):
    dep.pop(k, None)
mis = copy.deepcopy(next(m for m in src['alienMissions'] if m['type'] == 'STR_COBRA_BUILD_DEPOT'))
mis['type'] = 'STR_COBRA_BUILD_AIRSTRIP'
mis['siteType'] = 'STR_COBRA_AIRSTRIP_SITE'
scr = copy.deepcopy(next(s for s in src['missionScripts'] if s['type'] == 'cobraBuildDepot'))
scr['type'] = 'cobraBuildAirstrip'
scr['missionWeights'] = {0: {'STR_COBRA_BUILD_AIRSTRIP': 100}}
scr['missionVarName'] = 'COBRA_BUILD_STR_COBRA_AIRSTRIP'

out = {
    'alienDeployments': [dep],
    'alienMissions': [mis],
    'missionScripts': [scr],
    'extraStrings': [{'type': 'en-US', 'strings': {
        'STR_COBRA_AIRSTRIP': 'Cobra Airstrip',
        'STR_COBRA_AIRSTRIP_SITE': 'Cobra Airstrip',
        'STR_COBRA_BUILD_AIRSTRIP': 'Cobra builds an airstrip',
    }}],
}
hdr = ('# GENERATED by build/gen_cobra_airstrip.py: do not edit by hand.\n'
       '# Cobra\'s airstrip (FANG Operating Base): its Rattlers fly the air raids on Joe outposts (AIR_RAID_DESIGN_v1 s.1).\n'
       '# STAND-IN map: the factory site\'s, until COBRA_OUTPOSTS_v1 settles what an airstrip looks like.\n')
with open(os.path.join(RUL, 'gijoe_cobra_airstrip.rul'), 'w') as f:
    f.write(hdr + yaml.safe_dump(out, sort_keys=False, width=140))
print('airstrip: deployment, build mission, mission script written')
