"""materials.json -> the MCDPatches the engine actually reads.

tag_materials.py works out what 282 tiles are made of. Nothing was carrying those tags into the
game, so MapData::_material stayed 0 on every tile and the penetration matrix treated the whole
world as one undifferentiated wall. Plasterboard and reinforced concrete stopped a rifle round
identically. The feature was in the build, running, and inert - which is the worst of the three,
because it looks like it works.

A patch is keyed by dataset name and MCD index, which is exactly how the tags are keyed, so this
is a transcription and the only interesting part is refusing to transcribe what it cannot check.

TWO THINGS ARE VERIFIED, because both failures are quiet in different ways.

  THE COUNT MUST MATCH EXACTLY. MapDataSet::getObject throws on an out-of-range index, so an
  over-long tag list is at least loud. An index that is in range but describes a different tile
  is not loud at all: it silently makes a window out of concrete. Equal counts is the only
  evidence available here that the tagger and the game are looking at the same MCD, so a dataset
  whose MCD cannot be found, or whose record count disagrees, is REPORTED AND NOT EMITTED.

  A DATASET THE GAME LOADS AND NOBODY TAGGED IS A HOLE. It reads as MAT_UNKNOWN throughout and
  behaves like masonry, which is plausible enough to pass a playtest. The only way to find out is
  to list what the terrains load and subtract what is tagged, so that is printed too.

The terrain argument is a colon-separated list because a dataset's MCD can legitimately live
somewhere other than the mod's own folder - a vanilla one comes from the master's TERRAIN - and
refusing a dataset for being absent from the first place looked is a false negative that costs a
whole terrain its materials. That happened: NAWILD was refused as missing while the game was
loading it, and the only reason anyone found out was that the probe printed a line for it.

usage: apply_materials.py <materials.json> <terrain dir>[:<more>...] <ruleset dir> <out.rul>
"""
import sys, os, json, glob, re

MAT_JSON, TERRAIN, RULESET, OUT = sys.argv[1:5]
ROOTS = [p for p in TERRAIN.split(':') if p]

# MapData.h's CobraMaterial. Index is the value the ruleset carries.
MATERIALS = ['unknown', 'light', 'wood', 'masonry', 'concrete', 'metal']
MCD_RECORD = 62          # bytes per MCD record, fixed by the format

BUILTIN = {'BLANKS'}     # declared by every terrain, holds nothing to shoot


def mcd_records(name):
    """How many tiles the dataset on disk actually holds, or None if it is not here.

    Vanilla datasets live in the X-COM data the container does not have, so None is a normal
    answer and not an error - it just means this script cannot vouch for those indices."""
    for root in ROOTS:
        for cand in glob.glob(os.path.join(root, '**', name + '.MCD'), recursive=True):
            size = os.path.getsize(cand)
            if size % MCD_RECORD:
                return None          # not a whole number of records: not an MCD we understand
            return size // MCD_RECORD
    return None


def declared_datasets():
    """Every dataset the mod's terrains ask for.

    Parsed rather than hardcoded, so a terrain added later shows up in the hole report without
    anyone remembering to update a list."""
    found = set()
    for path in glob.glob(os.path.join(RULESET, '*.rul')):
        with open(path, encoding='utf-8', errors='replace') as fh:
            inside = False
            indent = None
            for line in fh:
                if re.match(r'^\s*mapDataSets:\s*$', line):
                    inside, indent = True, None
                    continue
                if not inside:
                    continue
                m = re.match(r'^(\s*)-\s*([A-Za-z0-9_]+)\s*$', line)
                if m and (indent is None or len(m.group(1)) == indent):
                    indent = len(m.group(1))
                    found.add(m.group(2).upper())
                    continue
                if line.strip() and not line.startswith(' '):
                    inside = False
                elif m is None and line.strip():
                    inside = False
    return found


tags = json.load(open(MAT_JSON))
emitted, refused = {}, []

for name in sorted(tags):
    rows = tags[name]
    have = mcd_records(name)
    if have is None:
        refused.append('%-10s %3d tags  NO MCD ON DISK - cannot confirm the indices line up, '
                       'so nothing emitted' % (name, len(rows)))
        continue
    if have != len(rows):
        refused.append('%-10s %3d tags vs %3d records in %s.MCD - the tagger and the game are '
                       'not looking at the same file' % (name, len(rows), have, name))
        continue
    emitted[name] = rows

lines = ['# GENERATED by build/apply_materials.py - do not hand-edit.',
         '#',
         '# What each tile is made of, for the penetration matrix. Values are MapData.h\'s',
         '# CobraMaterial: 1 light, 2 wood, 3 masonry, 4 concrete, 5 metal. A tile left out',
         '# reads as 0 (unknown), which the matrix prices like masonry.',
         '#',
         '# To override one tile, do it in a hand-written ruleset loaded after this one rather',
         '# than by editing here, or the next run of the generator throws the change away.',
         '']
if emitted:
    lines.append('MCDPatches:')
for name in sorted(emitted):
    rows = emitted[name]
    body = [(i, MATERIALS.index(m)) for i, m in enumerate(rows)
            if m in MATERIALS and MATERIALS.index(m) > 0]
    lines.append('  - type: %s' % name)
    lines.append('    data:')
    for idx, val in body:
        lines.append('      - MCDIndex: %d' % idx)
        lines.append('        material: %d' % val)

with open(OUT, 'w', encoding='utf-8') as fh:
    fh.write('\n'.join(lines) + '\n')

total = 0
for name in sorted(emitted):
    rows = emitted[name]
    counts = {m: rows.count(m) for m in MATERIALS if rows.count(m)}
    live = sum(v for k, v in counts.items() if k != 'unknown')
    total += live
    print('   %-10s %3d tiles  %s' % (name, live,
          '  '.join('%s %d' % (k, v) for k, v in sorted(counts.items()))))

print('\n   wrote %s  -  %d tiles patched across %d datasets' % (OUT, total, len(emitted)))

for r in refused:
    print('   REFUSED:', r)

untagged = declared_datasets() - set(tags) - BUILTIN
if untagged:
    print('\n   LOADED BY A TERRAIN AND NEVER TAGGED - every tile reads as unknown:')
    for name in sorted(untagged):
        have = mcd_records(name)
        print('      %-10s %s' % (name, ('%d tiles' % have) if have else 'count unknown here'))
