"""Every gun in the mod gets a visible shot (John 17 Nov 00:08: "Bullets you can see in flight ... i need this done for the next test").

gijoe_projectiles.rul (the sheet, 12 Nov) names only the stock X-COM item ids. The mod's own guns (gijoe_joe_guns.rul, the villains'
weapons, the vehicles, the Arsenal's 342 weapons) came later. This gives each of them a row of that sheet by what it fires:
  bullets 11 (heavy 12 at power 60+), lasers 13 Joe / 14 Cobra, pulse 15 Cobra / 16 Joe, grenade and lobbed rounds 17,
  rockets 18 and missiles 20 (both point where they fly).
Any gun still on a stock X-COM row (0-10: the 3-pixel dots, which is what the Arsenal set) is moved.
Read off the AMMO where a gun has ammo (the engine reads the ammo's bulletSprite first), else off the gun.
usage: python3 build/gen_projectile_assign.py  -> mod/Ruleset/zz_gijoe_projectile_assign.rul
"""
import glob, os, yaml
HERE = os.path.dirname(os.path.abspath(__file__))
RUL = os.path.join(HERE, '..', 'mod', 'Ruleset')
items = {}
for f in sorted(glob.glob(os.path.join(RUL, '*.rul'))):
    if os.path.basename(f) in ('zz_gijoe_projectile_assign.rul', 'gijoe_projectiles.rul'):
        continue
    try:
        d = yaml.safe_load(open(f)) or {}
    except Exception:
        continue
    for it in d.get('items', []) or []:
        if isinstance(it, dict) and it.get('type'):
            items.setdefault(it['type'], {}).update(it)
stock = {i['type'] for i in yaml.safe_load(open(os.path.join(RUL, 'gijoe_projectiles.rul')))['items']}
def kind(w, a):
    src = a or w
    dt = src.get('damageType', w.get('damageType', 1))
    name = (w.get('type', '') + ' ' + w.get('name', '') + ' ' + (a or {}).get('type', '')).upper()
    cobra = 'COBRA' in name
    if w.get('gjaGroup') == 'MISSILES' or 'MISSILE' in name:
        return 20, True
    if 'ROCKET' in name or ('LAUNCHER' in name and dt == 3 and not w.get('arcingShot')):
        return 18, True
    if dt == 3 and w.get('gjaGroup') in (None, 'GUNS') and not w.get('arcingShot') \
            and not any(x in name for x in ('GRENADE', 'MORTAR', 'LAUNCHER', 'BOMB')):
        return 12, False    # a cannon firing a shell: the heavy tracer, as gijoe_projectiles.rul gives the MOBAT's
    if dt == 3 or w.get('arcingShot') or w.get('gjaGroup') in ('ARTY', 'DROPS'):
        return 17, False
    if dt == 4:
        return (14 if cobra else 13), False
    if dt == 5:
        return (15 if cobra else 16), False
    p = src.get('power', 0) or 0
    return (12 if p >= 60 else 11), False
out = []
for t, w in sorted(items.items()):
    if w.get('battleType') != 1 or t in stock or (w.get('bulletSprite') or 0) >= 11:
        continue
    ammo = None
    for a in w.get('compatibleAmmo') or []:
        if a in items:
            ammo = items[a]; break
    row, directional = kind(w, ammo)
    # the gun and every round it takes: the engine reads the ammo's sprite first, so all of them are moved
    targets = [t] + [a for a in (w.get('compatibleAmmo') or []) if a in items and a not in stock and (items[a].get('bulletSprite') or 0) < 11]
    for target in targets:
        if any(x['type'] == target for x in out):
            continue
        e = {'type': target, 'bulletSprite': row}
        if directional:
            e['bulletDirectional'] = True
        out.append(e)
hdr = ('# GENERATED by build/gen_projectile_assign.py: do not edit by hand.\n'
       '# A visible shot for every gun the mod added after gijoe_projectiles.rul: rows of that sheet by what each gun fires.\n')
open(os.path.join(RUL, 'zz_gijoe_projectile_assign.rul'), 'w').write(hdr + yaml.safe_dump({'items': out}, sort_keys=False, default_flow_style=None, width=160))
from collections import Counter
print('projectiles assigned:', len(out), dict(Counter(e['bulletSprite'] for e in out)))
