"""The leader's call (BRIEF_FOR_BUILD_BattleAI 3; John 14:25): every Cobra site has men off the map whom its leader
can call in once - only while he is up, only after he has seen a Joe; they arrive three turns later
(engine: NextTurnState::runLeaderCall, reusing the onCall waves the van stop built).

Writes gijoe_leader_call.rul: one onCall wave per Cobra site deployment, its troopers carrying that site's own
trooper kit ladder (copied, so the calendar's kit cap still applies to them).
NOT modelled: arriving at the edge nearest the site's barracks (nothing marks a barracks on these maps); they come
in at a map edge away from the Joes.

usage: python3 build/gen_leader_call.py
"""
import copy, os, yaml

HERE = os.path.dirname(os.path.abspath(__file__))
RUL = os.path.join(HERE, '..', 'mod', 'Ruleset')
SOURCES = ['gijoe_cobra_sites.rul', 'gijoe_cobra_airstrip.rul', 'gijoe_frontops.rul']
LOW, HIGH = 2, 4          # men off the map (BUILD's first number)

out = []
for name in SOURCES:
    d = yaml.safe_load(open(os.path.join(RUL, name)))
    for dep in d.get('alienDeployments', []) or []:
        t = dep.get('type', '')
        if not (t.startswith('STR_COBRA_') and (t.endswith('_SITE') or t == 'STR_COBRA_FRONT')):
            continue
        trooper = next((e for e in dep.get('data', []) if e.get('alienRank') == 5), None)
        if not trooper:
            continue
        entry = {'alienRank': 5, 'lowQty': LOW, 'highQty': HIGH, 'dQty': 1,   # NOT percentageOutsideUfo: in a wave that key means 'spawn as civilians'
                 'itemSets': copy.deepcopy(trooper.get('itemSets', []))}
        out.append({'type': t, 'reinforcements': [{
            'type': 'LEADER_CALL', 'onCall': True, 'maxRuns': 1,
            'useSpawnNodes': False, 'maxDistanceFromBorders': 3, 'minDistanceFromXcomUnits': 12,
            'data': [entry]}]})

rul = {'alienDeployments': out,
       'extraStrings': [{'type': 'en-US', 'strings': {
           'STR_LEADER_CALLED': 'Cobra radio traffic: their officer has called for backup. Expect more of them in three turns.'}}]}
hdr = ('# GENERATED by build/gen_leader_call.py: do not edit by hand.\n'
       '# The leader\'s call (BRIEF_FOR_BUILD_BattleAI 3): 2-4 troopers off the map at every Cobra site, called in once.\n')
with open(os.path.join(RUL, 'gijoe_leader_call.rul'), 'w') as f:
    f.write(hdr + yaml.safe_dump(rul, sort_keys=False, width=140))
print('leader call: %d deployments' % len(out))
